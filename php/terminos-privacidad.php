        <section class="legal-section" id="privacidad">
            <h2>3. Política de privacidad y datos personales</h2>
            <h3>Datos que pueden tratarse</h3>
            <ul>
                <li><strong>Cuenta:</strong> nombre, cédula, correo electrónico, teléfono si se proporciona, contraseña almacenada mediante hash y fecha de registro.</li>
                <li><strong>Perfil:</strong> nickname, avatar, banner, biografía, ubicación, sitio web y preferencia de visibilidad, según lo que la persona usuaria agregue.</li>
                <li><strong>Actividad:</strong> publicaciones e imágenes, comentarios, reacciones, seguimientos, favoritos, mensajes y solicitudes que se generen al usar esas funciones.</li>
                <li><strong>Consultas:</strong> datos incluidos en preguntas o solicitudes enviadas a los formularios de soporte o al asistente turístico.</li>
                <li><strong>Recuperación de cuenta:</strong> código de verificación almacenado como hash, vencimiento e intentos. Para limitar abusos se guardan temporalmente identificadores hash derivados de la dirección IP y del correo ingresado.</li>
                <li><strong>Datos técnicos:</strong> información necesaria para mantener la sesión, recordar el idioma elegido, proteger el sitio y diagnosticar errores.</li>
            </ul>
            <h3>Finalidades y visibilidad</h3>
            <p>Estos datos se utilizan para crear y proteger cuentas, prestar las funciones solicitadas, mostrar perfiles y publicaciones conforme
                a las opciones de privacidad, gestionar interacciones, responder consultas y mantener la seguridad y operación del servicio.
                La información publicada en una galería o en un perfil público puede ser visible para cualquier visitante.</p>
            <p>SIGTUR no solicita que se publiquen contraseñas, datos financieros, documentos de identidad ni información sensible en perfiles,
                comentarios, mensajes o consultas al asistente. Evitá incluir información que no sea necesaria.</p>
            <h3>Servicios externos</h3>
            <p>La recuperación de contraseña envía el código al correo de la cuenta usando el servicio SMTP de Gmail configurado por el operador;
                Google procesa la dirección de destino y el contenido necesario para entregar ese mensaje. Algunas otras funciones pueden conectarse
                con proveedores externos. Los mapas pueden cargar contenido de Google Maps; las fuentes
                tipográficas se sirven desde Google Fonts; la traducción automática puede enviar el texto visible a MyMemory cuando se usa
                una traducción; y el asistente turístico puede procesar la pregunta y contexto público mediante el servicio de inteligencia
                artificial configurado por SIGTUR. Estos proveedores pueden recibir datos técnicos como la dirección IP y se rigen también
                por sus propias políticas. Los enlaces a redes sociales abren servicios sujetos a sus condiciones.</p>
            <h3>Comunicación, conservación y derechos</h3>
            <p>Los datos no deben compartirse para fines ajenos al funcionamiento del servicio, salvo autorización, necesidad operativa con
                proveedores, cumplimiento de obligaciones legales o protección de derechos y seguridad. Se conservan mientras sean necesarios
                para la cuenta, las funciones solicitadas y las obligaciones aplicables; los plazos concretos dependen del tipo de dato y de
                los requisitos legales y técnicos.</p>
            <p>Podés solicitar información sobre tus datos, su actualización o ejercer los derechos que reconozca la ley dirigiéndote al
                equipo de SIGTUR. Para proteger tu cuenta, es posible que se requiera verificar tu identidad por un canal adecuado.
                La eliminación de una publicación no necesariamente elimina copias o interacciones que deban conservarse legalmente o por
                motivos de seguridad.</p>
            <p>El navegador puede guardar la preferencia de idioma y datos de traducción en almacenamiento local. SIGTUR también utiliza
                sesiones técnicas para mantener el inicio de sesión y proteger formularios.</p>
        </section>

